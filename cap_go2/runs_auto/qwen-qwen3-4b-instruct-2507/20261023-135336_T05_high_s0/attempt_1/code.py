# 1辺1メートルの正方形を描く（counter-clockwise：左回り）
# 開始位置: (0.0, 0.0), 初期向き: 0 deg (x 軸方向)

# 1. 前に1メートル進む
move_forward(1.0)

# 2. 右に90度旋回（左回りが正なので、右回りは負）
turn(-90)

# 3. 右に1メートル進む（右は負）
move_forward(1.0)

# 4. 右に90度旋回（右回りなので -90）
turn(-90)

# 5. 右に1メートル進む
move_forward(1.0)

# 6. 右に90度旋回（右回りなので -90）
turn(-90)

# 7. 前に1メートル進む（元の位置に戻る）
move_forward(1.0)

# 最後に1秒間停止
stop(1.0)
