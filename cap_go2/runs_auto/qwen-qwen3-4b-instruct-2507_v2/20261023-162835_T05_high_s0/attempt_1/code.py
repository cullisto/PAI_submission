# 1辺1メートルの正方形を描くために、4つの辺を前進・右回りで移動する
# 開始位置: (0.0, 0.0), 初期向き: 0 deg (前方が+x方向)

# 辺の長さは1.0m
side_length = 1.0

# 1辺を前進（+x方向）して、その後45度右回り（-45度）に旋回して次の辺へ
# 45度旋回は左回りが正なので、右回りは負

# 1. 前進1.0m
move_forward(side_length)
print("前進1.0m")

# 2. 右に45度旋回（右回りなので -45度）
turn(-45)
print("右に45度旋回")

# 3. 前進1.0m（現在は+y方向）
move_forward(side_length)
print("前進1.0m")

# 4. 右に45度旋回
turn(-45)
print("右に45度旋回")

# 5. 前進1.0m（現在は-x方向）
move_forward(side_length)
print("前進1.0m")

# 6. 右に45度旋回
turn(-45)
print("右に45度旋回")

# 7. 前進1.0m（現在は-y方向）
move_forward(side_length)
print("前進1.0m")

# 8. ロボットは元の位置に戻るため、向きを0degに戻す（右回りで45度×4 = 180度）
turn(-180)
print("180度右回りで向きを元に戻す")

# 9. 最後に停止
stop(1.0)
