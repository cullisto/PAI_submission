# 1辺1メートルの正方形を描くように歩くが、正確な方向と距離を確保するために、
# 各移動後に向きを正確に調整し、元の位置に戻るようにする。
# 初期位置: (0.0, 0.0), 初期向き: 0 deg (x軸正方向)

# 正方形の1辺の長さ
side_length = 1.0

# 各辺の移動と旋回を明確に定義（0deg → 90deg → 180deg → 270deg → 360deg=0deg）
# 各移動は現在の向きに沿って前進、旋回はその場で右回り（負）に45度ずつ

# 1. 初期状態: (0.0, 0.0), 0 deg → +x方向に前進
move_forward(side_length)
print("前進1.0m (x方向)")

# 2. 右に45度旋回（右回りなので -45度） → 今の向きは -45 deg
turn(-45)
print("右に45度旋回")

# 3. +y方向に前進（現在の向きが+y方向に近づく）
move_forward(side_length)
print("前進1.0m (y方向)")

# 4. 右に45度旋回 → 向きは -90 deg（-y方向）
turn(-45)
print("右に45度旋回")

# 5. -x方向に前進（現在の向きが-x方向）
move_forward(side_length)
print("前進1.0m (-x方向)")

# 6. 右に45度旋回 → 向きは -135 deg（+x方向から右に45度回って -135deg）
turn(-45)
print("右に45度旋回")

# 7. -y方向に前進（現在の向きが-y方向）
move_forward(side_length)
print("前進1.0m (-y方向)")

# 8. 向きを元の0degに戻す（現在は -180 deg → 0degに調整）
turn(-180)
print("180度右回りで向きを元に戻す")

# 9. 最後に停止
stop(1.0)
