# 青い箱の位置を取得
bx, by = get_object_position("blue_box")

# 青い箱の裏側（スタート地点から見て反対側）に回り込むため、まず正確に向きを調整し、安全な距離で移動する
# ロボットの大きさを考慮して、青い箱の中心から0.35m（前後方向）後ろに位置するように移動
# まず、青い箱に向かって移動するが、直接移動すると物体にぶつかる可能性があるため、
# その前にロボットの向きを調整し、安全な距離で進むようにする

# スタートから青い箱に向かって移動（安全距離を確保）
# 青い箱の中心に近づくが、0.35m後ろに配置されるようにする
target_x = bx - 0.35
target_y = by

# ロボットの現在の向きを確認し、青い箱に向かって進むようにする
# まず、青い箱の中心に向かって旋回（向きを調整）
face(bx, by)

# その後、安全な距離（0.35m後ろ）まで移動（直接移動）
reached = move_to(target_x, target_y, tolerance=0.3, timeout=10.0)
print("安全な位置に到達:", reached)

# 到着後、青い箱の中心を向く（裏側に回り込んだ状態で）
face(bx, by)

# 最後に停止
stop(1.0)
