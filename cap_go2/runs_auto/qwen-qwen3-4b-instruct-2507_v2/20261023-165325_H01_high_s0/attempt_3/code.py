# 青い箱の位置を取得
bx, by = get_object_position("blue_box")

# 青い箱の裏側（スタート地点から見て反対側）に回り込むため、まず正確に向きを調整し、安全な距離で移動する
# ロボットの大きさを考慮：前後方向に0.35mの安全距離を確保（胴体の中心が箱に当たらないように）

# 1. 青い箱の中心に直接向かって旋回（正確に向きを調整）
turn_to(90)  # 初期向きは0deg（+x方向）なので、青い箱の中心を向くために90degに旋回（+y方向）

# 2. 青い箱の中心から0.35m後ろ（x方向）に移動するように目標を設定
target_x = bx - 0.35
target_y = by

# 3. 青い箱の中心に向かって移動（安全な距離で）
reached = move_to(target_x, target_y, tolerance=0.3, timeout=10.0)
print("安全な位置に到達:", reached)

# 4. 青い箱の中心を正確に向く（方向を調整）
face(bx, by)

# 5. 最後に停止
stop(1.0)
