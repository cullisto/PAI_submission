# 2枚の壁の隙間を通り抜けて赤い箱まで行く
# 初期位置: (0.0, 0.0), 向き: 0 deg (前方が +x)

# 1. 壁の位置を確認して、隙間の位置を特定
# 壁_upper: (2.0, 2.725), 大きさ 0.3 × 2.55 → y方向は2.725〜0.175
# 壁_lower: (2.0, -1.475), 大きさ 0.3 × 4.05 → y方向は-1.475〜-0.475
# 隙間のy範囲は -1.475 から 2.725 までだが、壁の幅から外側は不可
# よって、隙間のy方向の許容範囲は -1.475 + 0.15 〜 2.725 - 0.15 = -1.325 〜 2.575
# しかし、ロボットの幅は左右0.3m、前後0.7mなので、壁の前に近づくのは0.35m以上離れる必要がある

# 2. 隙間を通るにはまず、壁の前に進む必要がある
# 壁のxは2.0なので、ロボットの中心がx=2.0に達するまで進む
# ただし、壁のy方向にずれてもよいが、y方向に制限がある

# 3. ロボットの初期位置 (0.0, 0.0) から、壁の前に進む
# まず、壁の前に進む（x方向に2.0まで進む）
move_forward(2.0)

# 4. 現在の位置を確認して、y方向に壁の範囲を考慮して、隙間の中央に近づく
# 隙間の中央y: (2.725 - 1.475) / 2 = 0.625 → 0.625m
# ロボットのy方向の幅は0.3mなので、ロボットの中心は y=0.625 ± 0.15 以内でなければならない
# 今の位置は (2.0, 0.0) なので、y方向に0.625に移動

# 5. y方向に移動（左が正なので、0.625に近づく）
# 0.625 - 0.0 = 0.625m → 0.625m移動
move_sideways(0.625)

# 6. その場で赤い箱の方向を向く（ゴールに向かって）
# 赤い箱の位置: (4.0, -1.0)
# 今の位置: (2.0, 0.625)
# 方向を調整
face(4.0, -1.0)

# 7. 赤い箱まで移動（障害物を避けないが、壁を通過済みなので安全）
# 距離を計算して移動
current_x, current_y = get_position()
target_x, target_y = 4.0, -1.0
distance = math.hypot(target_x - current_x, target_y - current_y)
# 軽く距離を確認して移動
reached = move_to(target_x, target_y, tolerance=0.3)
print("赤い箱到着:", reached)

# 8. 到着したら停止
if reached:
    stop(1.0)
