# 前回の失敗原因: 障害物に近づいてしまう（壁にぶつかる）ため、移動前に正確に障害物の範囲を考慮してコースを設計

# 1. 初期位置: (0.0, 0.0), 向き: 0 deg
# 壁_upper: (2.0, 2.725), 大きさ 0.3×2.55 → y方向: 2.725 - 2.55 = 0.175 から 2.725 まで → 下限 y=0.175
# 壁_lower: (2.0, -1.475), 大きさ 0.3×4.05 → y方向: -1.475 - 4.05 = -5.525 から -1.475 まで → 上限 y=-1.475
# よって、壁の間に隙間があるのは y ∈ [-1.475 + 0.15, 2.725 - 0.15] = [-1.325, 2.575] まで
# ロボットの幅は左右0.3m、前後0.7m → 障害物との距離は、壁の表面から0.15m以上離れる必要がある

# 2. よって、x=2.0 に到達する前に、y方向に壁の範囲内に収まるように移動
